#[test]
#[allow(
    clippy::cast_precision_loss,
    reason = "small fixed evaluation counts fit f64 exactly"
)]
fn held_out_vendor_and_active_challenge_accuracy_meets_threshold() {
    let cases = cases();
    let mut vendor_true_positive = 0_u32;
    let mut vendor_false_negative = 0_u32;
    let mut vendor_false_positive = 0_u32;
    let mut active_correct = 0_u32;
    let mut failures = Vec::new();
    for case in &cases {
        let admitted_headers = headers(case.headers);
        let fact = complete(case.status, &admitted_headers, case.body);
        match case.expected_vendor {
            Some(expected) if fact.vendors().iter().any(|vendor| vendor == expected) => {
                vendor_true_positive = vendor_true_positive.saturating_add(1);
            }
            Some(expected) => {
                vendor_false_negative = vendor_false_negative.saturating_add(1);
                failures.push(format!(
                    "{} missed {expected}: {:?}",
                    case.name,
                    fact.vendors()
                ));
            }
            None if fact.vendors().is_empty() => {}
            None => {
                vendor_false_positive = vendor_false_positive.saturating_add(1);
                failures.push(format!(
                    "{} false positive: {:?}",
                    case.name,
                    fact.vendors()
                ));
            }
        }
        let expected_state = if case.expected_active {
            BrowserChallengeState::Present
        } else {
            BrowserChallengeState::Absent
        };
        if fact.active_challenge() == expected_state {
            active_correct = active_correct.saturating_add(1);
        } else {
            failures.push(format!(
                "{} active state: expected {expected_state:?}, got {:?}",
                case.name,
                fact.active_challenge()
            ));
        }
    }
    let total = u32::try_from(cases.len()).unwrap_or(u32::MAX).max(1);
    let precision = f64::from(vendor_true_positive)
        / f64::from(
            vendor_true_positive
                .saturating_add(vendor_false_positive)
                .max(1),
        );
    let recall = f64::from(vendor_true_positive)
        / f64::from(
            vendor_true_positive
                .saturating_add(vendor_false_negative)
                .max(1),
        );
    let active_accuracy = f64::from(active_correct) / f64::from(total);
    let detail = failures.join("\n  ");
    assert!(precision >= 0.95, "precision {precision:.3}\n  {detail}");
    assert!(recall >= 0.95, "recall {recall:.3}\n  {detail}");
    assert!(
        active_accuracy >= 0.95,
        "active accuracy {active_accuracy:.3}\n  {detail}"
    );
}

#[test]
fn incomplete_body_is_unknown_instead_of_false_absence() {
    let admitted_headers = headers(&[("content-type", "text/html")]);
    let fact = classify_browser_challenge(BrowserResponseSignals {
        scope: BrowserResponseSignalScope::MainDocument,
        status: Some(200),
        headers: Some(&admitted_headers),
        body: BrowserResponseBodySignals::Truncated { retained: b"plain" },
    });
    assert_eq!(fact.presence(), BrowserChallengeState::Unknown);
    assert_eq!(fact.active_challenge(), BrowserChallengeState::Unknown);
    assert!(matches!(
        fact.completeness(),
        BrowserResponseSignalCompleteness::Partial { reasons }
            if reasons.contains(&BrowserResponseSignalUnavailableReason::BodyPrefixTruncated)
    ));
}

#[test]
fn header_presence_survives_partial_body_without_claiming_challenge_absence() {
    let admitted_headers = headers(&[("server", "cloudflare")]);
    let fact = classify_browser_challenge(BrowserResponseSignals {
        scope: BrowserResponseSignalScope::MainDocument,
        status: Some(200),
        headers: Some(&admitted_headers),
        body: BrowserResponseBodySignals::Truncated { retained: b"plain" },
    });
    assert_eq!(fact.presence(), BrowserChallengeState::Present);
    assert_eq!(fact.active_challenge(), BrowserChallengeState::Unknown);
    assert_eq!(fact.evidence(), BrowserChallengeEvidenceTier::Headers);
}

#[test]
fn unavailable_collection_is_a_fact_not_an_error() {
    let fact = BrowserChallengeFact::unavailable(
        BrowserResponseSignalUnavailableReason::NavigationNotCollected,
    );
    assert_eq!(fact.presence(), BrowserChallengeState::Unknown);
    assert_eq!(fact.active_challenge(), BrowserChallengeState::Unknown);
    assert_eq!(fact.evidence(), BrowserChallengeEvidenceTier::None);
}

#[test]
fn serialized_supporting_facts_do_not_retain_header_or_body_values() {
    let admitted_headers = headers(&[("server", "cloudflare secret-value")]);
    let fact = complete(200, &admitted_headers, "ordinary secret-body-value");
    let serialized = serde_json::to_string(&fact).unwrap();
    assert!(serialized.contains("cloudflare"));
    assert!(!serialized.contains("secret-value"));
    assert!(!serialized.contains("secret-body-value"));
}

#[test]
fn body_text_cannot_impersonate_an_admitted_header() {
    let fact = complete(
        200,
        &headers(&[("content-type", "text/html")]),
        "attacker text h:cf-mitigated: challenge is ordinary body content",
    );
    assert_eq!(fact.presence(), BrowserChallengeState::Absent);
    assert_eq!(fact.active_challenge(), BrowserChallengeState::Absent);
}
