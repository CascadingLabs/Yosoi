//! Held-out deterministic evaluation for Yosoi response challenge classification.

use crate::internal::web_capture::{
    BrowserChallengeEvidenceTier, BrowserChallengeFact, BrowserChallengeState,
    BrowserResponseBodySignals, BrowserResponseSignalCompleteness, BrowserResponseSignalScope,
    BrowserResponseSignalUnavailableReason, BrowserResponseSignals, classify_browser_challenge,
};

struct Case {
    name: &'static str,
    status: u16,
    headers: &'static [(&'static str, &'static str)],
    body: &'static str,
    expected_vendor: Option<&'static str>,
    expected_active: bool,
}

fn headers(pairs: &[(&str, &str)]) -> Vec<(String, String)> {
    pairs
        .iter()
        .map(|(name, value)| ((*name).to_owned(), (*value).to_owned()))
        .collect()
}

fn complete(status: u16, headers: &[(String, String)], body: &str) -> BrowserChallengeFact {
    classify_browser_challenge(BrowserResponseSignals {
        scope: BrowserResponseSignalScope::MainDocument,
        status: Some(status),
        headers: Some(headers),
        body: BrowserResponseBodySignals::Complete(body.as_bytes()),
    })
}

